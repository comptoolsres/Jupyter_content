@app.cell
def _(Path, pypdf):
    # Use pypdf to read a PDF file and extract text from it
    pdf_path = Path('Himes_etal_2014.pdf')  # Replace with your PDF file path
    with open(pdf_path, 'rb') as f:
        reader = pypdf.PdfReader(f)
        text = ''
        for page in reader.pages:
            text = text + page.extract_text()
    # Print the first 500 characters of the extracted text
    print(text[:500])
    return (text,)


